export function normalizeHeroSlide(body = {}) {
  const deviceMode = ["both", "monitor", "phone"].includes(body.deviceMode)
    ? body.deviceMode
    : body.showPhone === false
      ? "monitor"
      : "both";

  return {
    id: String(body.id || ""),
    active: body.active !== false,
    order: Number(body.order || 0) || 0,
    eyebrow: String(body.eyebrow || ""),
    title: String(body.title || ""),
    highlight: String(body.highlight || ""),
    subtitle: String(body.subtitle || ""),
    ctaText: String(body.ctaText || ""),
    ctaLink: String(body.ctaLink || ""),
    secondaryCtaText: String(body.secondaryCtaText || ""),
    secondaryCtaLink: String(body.secondaryCtaLink || ""),
    backgroundImage: String(body.backgroundImage || ""),
    image: String(body.image || ""),
    imageAlt: String(body.imageAlt || ""),
    deviceMode,
    showPhone: deviceMode !== "monitor",
    phoneImage: String(body.phoneImage || ""),
    phoneLabel: body.phoneLabel === undefined ? "CREATIVOX · APK" : String(body.phoneLabel),
    phoneBadge: body.phoneBadge === undefined ? "APK · Android" : String(body.phoneBadge),
    previewLabel: String(body.previewLabel || ""),
    previewKicker: String(body.previewKicker || ""),
    previewText: String(body.previewText || ""),
    previewBadge: String(body.previewBadge || ""),
    stat1Value: String(body.stat1Value || ""),
    stat1Label: String(body.stat1Label || ""),
    stat2Value: String(body.stat2Value || ""),
    stat2Label: String(body.stat2Label || ""),
    stat3Value: String(body.stat3Value || ""),
    stat3Label: String(body.stat3Label || ""),
  };
}
